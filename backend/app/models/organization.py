"""
Organizations and organization invitations (membership security fix).

Before this, an "organization" was nothing but a string on each row, and
POST /auth/register let anyone choose that string -- so anyone could sign
up straight into an existing organization (and the first account to name
a fresh string became its admin by a user count). Now:

  - `organizations` is the authoritative list of tenants. IDs are
    generated by the server (`new_organization_id()`), never chosen by a
    caller. Public signup can only CREATE a new organization, and its
    creator becomes admin in the same transaction (app/services/membership_service.py).
  - Joining an EXISTING organization requires an `organization_invitations`
    row issued by one of its admins: bound to one email address, one
    organization and one role, expiring, single-use. Only a SHA-256 hash
    of the invitation token is stored, so a database read does not hand
    out working invitations.
"""

import secrets
import uuid
from datetime import UTC, datetime

from sqlalchemy import DateTime, String
from sqlalchemy.orm import Mapped, mapped_column

from app.database.session import Base
from app.models.spam_prediction_log import GUID


def new_organization_id() -> str:
    return f"org_{secrets.token_hex(8)}"


class Organization(Base):
    __tablename__ = "organizations"

    id: Mapped[str] = mapped_column(String(100), primary_key=True)
    name: Mapped[str] = mapped_column(String(200))
    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(GUID(), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(UTC))


class OrganizationInvitation(Base):
    __tablename__ = "organization_invitations"

    id: Mapped[uuid.UUID] = mapped_column(GUID(), primary_key=True, default=uuid.uuid4)
    organization_id: Mapped[str] = mapped_column(String(100), index=True)
    # Stored lower-cased; acceptance must present the same address.
    email: Mapped[str] = mapped_column(String(255), index=True)
    role: Mapped[str] = mapped_column(String(20))

    token_hash: Mapped[str] = mapped_column(String(64), unique=True)

    created_by_user_id: Mapped[uuid.UUID] = mapped_column(GUID())
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(UTC))
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))

    accepted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    accepted_by_user_id: Mapped[uuid.UUID | None] = mapped_column(GUID(), nullable=True)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
